DO $do$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'estoque_app') THEN
    CREATE ROLE estoque_app NOLOGIN NOSUPERUSER INHERIT NOCREATEDB NOCREATEROLE NOREPLICATION;
  END IF;
END
$do$;

REVOKE CONNECT ON DATABASE estoque FROM PUBLIC;
GRANT CONNECT ON DATABASE estoque TO estoque_app;

REVOKE CONNECT ON DATABASE template1 FROM PUBLIC;

GRANT USAGE, CREATE ON SCHEMA public TO estoque_app;
GRANT ALL ON ALL TABLES IN SCHEMA public TO estoque_app;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO estoque_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO estoque_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO estoque_app;
